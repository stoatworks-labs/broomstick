#!/usr/bin/env node
/**
 * Copy Test Card's Halloween artwork into src/art/.
 *
 * The witch, the dead trees, the bats, the lanterns and the gravestones are
 * Test Card's drawings (~/Projects/video/test-card, src/patterns/art/), not
 * redrawings of them. They are pure functions that return polygons, so they
 * come across as source, with two import paths rewritten and nothing else
 * touched. Everything in src/art/ is generated: change a drawing in Test Card
 * and run this again.
 *
 * Reads Test Card's committed `main`, not its working tree: that checkout is
 * shared with other sessions, and their half-finished edits are not artwork.
 *
 *   node scripts/sync-art.mjs           write src/art/
 *   node scripts/sync-art.mjs --check   exit 1 if src/art/ is not what it would write
 *
 * TEST_CARD=<path> and TEST_CARD_REF=<ref> point it somewhere else.
 */

import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { homedir } from 'node:os'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const out = join(here, '..', 'src', 'art')
const repo = process.env.TEST_CARD ?? join(homedir(), 'Projects', 'video', 'test-card')
const ref = process.env.TEST_CARD_REF ?? 'main'
const check = process.argv.includes('--check')

const git = (...args) => execFileSync('git', ['-C', repo, ...args], { encoding: 'utf8' })
const show = (path) => git('show', `${ref}:${path}`)

if (!existsSync(repo)) {
  console.error(`no Test Card checkout at ${repo} (set TEST_CARD)`)
  process.exit(2)
}
const sha = git('rev-parse', '--short', ref).trim()

/** [source in Test Card, file here, import rewrites] */
const FILES = [
  ['src/patterns/art/shapes.ts', 'shapes.ts', []],
  ['src/patterns/art/scenery.ts', 'scenery.ts', [["from '../random'", "from './random'"]]],
  ['src/patterns/art/halloween.ts', 'halloween.ts', [["from '../random'", "from './random'"], ["from '../../types'", "from './types'"]]],
  ['src/patterns/random.ts', 'random.ts', []],
]

const header = (from) =>
  `// GENERATED by scripts/sync-art.mjs from test-card ${from} at ${sha}.\n` +
  `// Do not edit: change the drawing in Test Card and run \`npm run sync-art\`.\n\n`

const files = new Map()
for (const [from, to, rewrites] of FILES) {
  let text = show(from)
  for (const [a, b] of rewrites) {
    if (!text.includes(a)) throw new Error(`${from} no longer contains ${a}: update the rewrites`)
    text = text.split(a).join(b)
  }
  files.set(to, header(from) + text)
}

// halloween.ts wants one type from Test Card's types.ts, which is mostly about
// outputs and exports. Take that one line rather than the whole file.
const types = show('src/types.ts')
const face = types.match(/^export type PumpkinFace = .*$/m)
if (!face) throw new Error('src/types.ts no longer declares PumpkinFace on one line')
files.set('types.ts', header('src/types.ts (PumpkinFace only)') + face[0] + '\n')

let stale = 0
for (const [name, text] of files) {
  const path = join(out, name)
  const now = existsSync(path) ? readFileSync(path, 'utf8') : null
  if (now === text) continue
  if (check) {
    console.error(`src/art/${name} differs from test-card ${ref} (${sha})`)
    stale++
  } else {
    writeFileSync(path, text)
    console.log(`wrote src/art/${name}`)
  }
}
if (check && stale) process.exit(1)
if (check) console.log(`src/art/ matches test-card ${ref} (${sha})`)
